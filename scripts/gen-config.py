#!/usr/bin/env python3
"""Generate vayu's config for the vendored ACK tree from a 5.4 config.

The input is the config chain LineageOS 24.0 actually boots on this device
(`vendor/sm8150-qgki_defconfig` + `vendor/xiaomi/sm8150-common.config` +
`vendor/xiaomi/vayu.config`, i.e. the running kernel's `.config`). The output
keeps every setting whose symbol still exists in the target kernel; anything
the target no longer defines is dropped and listed, because kconfig would
ignore it anyway and silently keeping it would hide how much of the vendor
config has no 6.18 counterpart.

    ./scripts/gen-config.py SOURCE.config kernel/ configs/vayu-android17.config \
        --dropped configs/vayu-android17.dropped

Exit status is non-zero if a symbol in `--fragment` does not exist in the
target tree, so a typo cannot quietly become a no-op.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DEFINE = re.compile(r"^\s*(?:menu)?config\s+([A-Za-z0-9_]+)\s*$")
SET = re.compile(r"^(CONFIG_[A-Za-z0-9_]+)=(.*)$")
UNSET = re.compile(r"^# (CONFIG_[A-Za-z0-9_]+) is not set$")

# Recomputed by kconfig on every build; carrying 5.4's toolchain identity into a
# 6.18 tree is noise at best and misleading at worst.
AUTO = {
    "CONFIG_CC_VERSION_TEXT", "CONFIG_CC_IS_GCC", "CONFIG_CC_IS_CLANG",
    "CONFIG_GCC_VERSION", "CONFIG_CLANG_VERSION", "CONFIG_AS_IS_GNU",
    "CONFIG_AS_IS_LLVM", "CONFIG_AS_VERSION", "CONFIG_LD_IS_BFD",
    "CONFIG_LD_IS_LLD", "CONFIG_LD_VERSION", "CONFIG_LLD_VERSION",
    "CONFIG_RUSTC_VERSION", "CONFIG_RUSTC_LLVM_VERSION",
    "CONFIG_PAHOLE_VERSION",
}

# Deliberate deltas from the 5.4 value, each with a reason.
OVERRIDES = {
    # The device reports "-qgki_aman" for a 5.4 vendor kernel; a 6.18 mainline
    # build has to be distinguishable in `uname -r`.
    "CONFIG_LOCALVERSION": 'CONFIG_LOCALVERSION="-vayu-mainline"',
}


def target_symbols(kernel: Path) -> set[str]:
    """Every `config FOO` symbol defined by the target tree's Kconfig files."""
    symbols: set[str] = set()
    for path in kernel.rglob("Kconfig*"):
        rel = path.relative_to(kernel).as_posix()
        # tools/ and Documentation/ carry their own unrelated config systems.
        if rel.startswith(("tools/", "Documentation/")):
            continue
        try:
            text = path.read_text(errors="replace")
        except OSError:
            continue
        for line in text.splitlines():
            match = DEFINE.match(line)
            if match:
                symbols.add("CONFIG_" + match.group(1))
    return symbols


def read_config(path: Path) -> dict[str, str]:
    entries: dict[str, str] = {}
    for line in path.read_text(errors="replace").splitlines():
        line = line.rstrip()
        match = SET.match(line) or UNSET.match(line)
        if match:
            entries[match.group(1)] = line
    return entries


def write_lf(path: Path, text: str) -> None:
    """Write UTF-8 with LF endings whatever platform this runs on."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", type=Path, help="5.4 .config from the LineageOS chain")
    ap.add_argument("kernel", type=Path, help="target kernel tree")
    ap.add_argument("out", type=Path, help="filtered config to write")
    ap.add_argument("--dropped", type=Path, help="write dropped symbols here")
    ap.add_argument("--fragment", type=Path,
                    help="extra fragment whose symbols must exist in the target")
    args = ap.parse_args()

    symbols = target_symbols(args.kernel)
    if not symbols:
        print(f"no Kconfig symbols found under {args.kernel}", file=sys.stderr)
        return 1

    entries = read_config(args.source)
    kept: dict[str, str] = {}
    dropped: list[str] = []
    for name, line in entries.items():
        if name in AUTO:
            continue
        if name in symbols:
            kept[name] = line
        else:
            dropped.append(name)

    # The fragment is applied here, not by merge_config.sh in CI: the committed
    # config file is then exactly what the build starts from, and a duplicate
    # "is not set" line in the filtered source cannot resurrect itself.
    if args.fragment:
        for line in args.fragment.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            match = SET.match(line) or UNSET.match(line)
            if match:
                kept[match.group(1)] = line

    kept.update(OVERRIDES)

    header = [
        "#",
        "# vayu / Android 17 - generated by scripts/gen-config.py, do not edit.",
        f"# source: {args.source}",
        "# kept: %d symbols | dropped: %d (no counterpart in the target Kconfig)"
        % (len(kept), len(dropped)),
        "#",
    ]
    body = [kept[name] for name in sorted(kept)]
    write_lf(args.out, "\n".join(header + body) + "\n")

    if args.dropped:
        write_lf(args.dropped,
                 "# Symbols in the source config that the target kernel does not define.\n"
                 "# Expected: the entire Qualcomm techpack/KGSL/SDE/Ion generation.\n"
                 + "\n".join(sorted(dropped)) + "\n")

    print(f"source symbols : {len(entries)}")
    print(f"kept           : {len(kept)} (includes {len(OVERRIDES)} override(s))")
    print(f"dropped        : {len(dropped)}")
    print(f"wrote          : {args.out}")

    if args.fragment:
        unknown = []
        for line in args.fragment.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            match = SET.match(line) or UNSET.match(line)
            if not match:
                unknown.append(f"unparsable line: {line}")
            elif match.group(1) not in symbols:
                unknown.append(f"{match.group(1)} not in target Kconfig")
        if unknown:
            print("\nfragment references symbols the target does not have:",
                  file=sys.stderr)
            for item in unknown:
                print(f"  {item}", file=sys.stderr)
            return 1
        print(f"fragment       : {args.fragment} (all symbols exist)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
